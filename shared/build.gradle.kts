val f1BaseUrlProvider = providers.gradleProperty("f1.api.base_url")
    .orElse("https://api.jolpi.ca/ergast/f1/")

val generateApiConfig = tasks.register("generateApiConfig") {
    val outputDir = layout.buildDirectory.dir("generated/apiconfig/kotlin")
    val urlProvider = f1BaseUrlProvider
    inputs.property("baseUrl", urlProvider)
    outputs.dir(outputDir)
    doLast {
        val baseUrl = urlProvider.get()
        val targetFile = outputDir.get().file("com/example/apex/data/ApiConfig.kt").asFile
        targetFile.parentFile.mkdirs()
        targetFile.writeText(
            """
            package com.example.apex.data

            object ApiConfig {
                const val baseUrl: String = "$baseUrl"
            }
            """.trimIndent()
        )
    }
}

